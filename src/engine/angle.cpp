// ANGLE::Sin/Cos are header-visible; VC6 chooses inline/shared COMDAT naturally.

// The retail Y tables are byte-identical to the normal sin/cos tables in this EXE.
float ANGLE::SinY()
{
    return FSin[value];
}

float ANGLE::CosY()
{
    return FCos[value];
}


// ANGLE::RotateX/RotateY are header-visible mylib helpers.

int ANGLE::Int() { return static_cast<int>(value); }

int ANGLE::operator<(const ANGLE* other)
{
    return static_cast<int>(value) < static_cast<int>(other->value);
}

int ANGLE::operator<=(const ANGLE* other)
{
    return static_cast<int>(value) <= static_cast<int>(other->value);
}

int ANGLE::operator>(const ANGLE* other)
{
    return static_cast<int>(value) > static_cast<int>(other->value);
}

ANGLE ANGLE::GetInversed()
{
    return ANGLE(static_cast<uint8_t>(static_cast<unsigned int>(value)+0x80u));
}

void ANGLE::Inverse()
{
    value=static_cast<uint8_t>(static_cast<unsigned int>(value)+0x80u);
}

ANGLE ANGLE::Difference(const ANGLE* other)
{
    const uint8_t d1=static_cast<uint8_t>(static_cast<unsigned int>(value)-other->value);
    const uint8_t d2=static_cast<uint8_t>(static_cast<unsigned int>(other->value)-value);
    return ANGLE(static_cast<uint8_t>(d1<d2 ? d1 : d2));
}

